// Generate the bridge contract from Go methods and JSON DTOs.
package main

import (
	"flag"
	"fmt"
	"os"
	"reflect"
	"strings"
	"wintoolbox/internal/ui"
)

func ts(t reflect.Type) string {
	switch t.Kind() {
	case reflect.Bool:
		return "boolean"
	case reflect.String:
		return "string"
	case reflect.Int, reflect.Int32, reflect.Int64, reflect.Uint, reflect.Uint32, reflect.Uint64, reflect.Float32, reflect.Float64:
		return "number"
	case reflect.Slice, reflect.Array:
		return "Array<" + ts(t.Elem()) + ">"
	case reflect.Pointer:
		return ts(t.Elem()) + " | null"
	case reflect.Struct:
		var fields []string
		for i := 0; i < t.NumField(); i++ {
			f := t.Field(i)
			if !f.IsExported() {
				continue
			}
			name := strings.Split(f.Tag.Get("json"), ",")[0]
			if name == "-" {
				continue
			}
			if name == "" {
				name = f.Name
			}
			optional := ""
			if strings.Contains(f.Tag.Get("json"), "omitempty") {
				optional = "?"
			}
			fields = append(fields, fmt.Sprintf("%s%s: %s", name, optional, ts(f.Type)))
		}
		return "{ " + strings.Join(fields, "; ") + " }"
	default:
		panic("unsupported bridge type: " + t.String())
	}
}

func main() {
	check := flag.Bool("check", false, "check generated contract without writing")
	flag.Parse()
	var out strings.Builder
	out.WriteString("// Generated by go run ./scripts/genbindings; do not edit.\nexport interface App {\n")
	t := reflect.TypeOf(ui.NewApp())
	errType := reflect.TypeOf((*error)(nil)).Elem()
	for i := 0; i < t.NumMethod(); i++ {
		m := t.Method(i)
		if m.Name == "Startup" {
			continue
		}
		var args []string
		for j := 1; j < m.Type.NumIn(); j++ {
			args = append(args, fmt.Sprintf("arg%d: %s", j, ts(m.Type.In(j))))
		}
		result := "void"
		for j := 0; j < m.Type.NumOut(); j++ {
			if m.Type.Out(j) != errType {
				result = ts(m.Type.Out(j))
				break
			}
		}
		fmt.Fprintf(&out, "  %s(%s): Promise<%s>\n", m.Name, strings.Join(args, ", "), result)
	}
	out.WriteString("}\nexport declare function wailsApp(): App | null\nexport declare function wailsCall<K extends keyof App>(method: K, ...args: Parameters<App[K]>): ReturnType<App[K]>\n")
	path := "frontend/src/api/wails.d.ts"
	if *check {
		data, err := os.ReadFile(path)
		if err != nil || string(data) != out.String() {
			fmt.Fprintln(os.Stderr, "Bridge contract is stale; run go run ./scripts/genbindings")
			os.Exit(1)
		}
		return
	}
	if err := os.WriteFile(path, []byte(out.String()), 0644); err != nil {
		panic(err)
	}
}
